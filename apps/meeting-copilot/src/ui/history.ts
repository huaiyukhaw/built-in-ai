import { deleteMeeting, listMeetings } from '../lib/db';
import { durationLabel } from '../lib/transcript';
import type { Meeting } from '../lib/model';
import { h } from './dom';
import { icon, renderAppBar, snackbar } from './shell';

export function renderHistory(root: HTMLElement, onOpen: (id: string) => void, onNew: () => void) {
  const search = h('input', { type: 'search', id: 'search', placeholder: 'Search meetings', autocomplete: 'off', 'aria-label': 'Search meetings' });
  renderAppBar({ center: h('label', { class: 'pill-field', for: 'search' }, icon('search'), search) });

  const results = h('ul', { class: 'meeting-list', 'aria-labelledby': 'history-heading' });
  const count = h('p', { class: 'count', role: 'status' });
  const empty = h('div', { class: 'empty', hidden: true },
    icon('groups'),
    h('h2', {}, 'No meetings yet'),
    h('p', {}, 'Start a meeting to see live captions in your language. Q&A and minutes are generated on this device.'),
    h('button', { class: 'btn-filled', on: { click: onNew } }, icon('add'), 'New meeting'));

  const confirm = h('dialog', { id: 'confirm-delete', 'aria-labelledby': 'confirm-title', 'aria-describedby': 'confirm-desc', closedby: 'any' },
    h('h2', { id: 'confirm-title' }, 'Delete meeting?'),
    h('p', { id: 'confirm-desc', class: 'muted' }, 'The transcript and minutes will be removed from this device. This can’t be undone.'),
    h('form', { method: 'dialog', class: 'dialog-actions' },
      h('button', { value: 'cancel', autofocus: true, class: 'btn-text' }, 'Cancel'),
      h('button', { value: 'delete', class: 'btn-text', style: '--fg: var(--error)' }, 'Delete')));

  root.replaceChildren(h('div', { class: 'history' },
    h('div', { class: 'history-head' },
      h('div', {},
        h('h1', { id: 'history-heading', tabindex: '-1' }, 'Your meetings'),
        h('p', {}, 'Live captions, answers and minutes — generated by Chrome’s built-in AI. Nothing leaves this device.')),
      h('button', { class: 'btn-filled btn-hero', on: { click: onNew } }, icon('add'), 'New meeting')),
    count, results, empty, confirm));

  const row = (m: Meeting) => {
    const items = m.minutes?.actionItems.length ?? 0;
    return h('li', { class: 'meeting-row' },
      h('span', { class: 'avatar' }, icon(m.minutes ? 'minutes' : 'groups')),
      h('a', { href: `#/m/${m.id}`, on: { click: (e: Event) => { e.preventDefault(); onOpen(m.id); } } },
        h('span', { class: 'row-title' }, m.title),
        h('span', { class: 'row-sub' },
          `${new Date(m.startedAt).toLocaleString(undefined, { weekday: 'short', day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' })} · ${durationLabel(m)} · ${m.segments.length} line${m.segments.length === 1 ? '' : 's'}`)),
      h('span', { class: 'tags' },
        m.minutes
          ? h('span', { class: 'tag ok' }, icon('check'), `${items} action item${items === 1 ? '' : 's'}`)
          : h('span', { class: 'tag' }, 'No minutes')),
      h('button', {
        class: 'icon-btn', 'aria-label': `Delete ${m.title}`, title: 'Delete',
        on: { click: () => {
          confirm.returnValue = '';
          confirm.onclose = async () => {
            if (confirm.returnValue === 'delete') { await deleteMeeting(m.id); await refresh(); snackbar('Meeting deleted'); search.focus(); }
            confirm.returnValue = '';
          };
          confirm.showModal();
        } },
      }, icon('delete')));
  };

  async function refresh() {
    const list = await listMeetings(search.value);
    results.replaceChildren(...list.map(row));
    const q = search.value.trim();
    empty.hidden = Boolean(list.length || q);
    results.hidden = !list.length;
    count.textContent = q
      ? `${list.length} result${list.length === 1 ? '' : 's'} for “${q}”`
      : list.length ? `${list.length} meeting${list.length === 1 ? '' : 's'} · saved on this device` : '';
  }

  let t: ReturnType<typeof setTimeout>;
  search.addEventListener('input', () => { clearTimeout(t); t = setTimeout(refresh, 150); });
  return refresh();
}
