// Generates src/styles/icons.css: Material Symbols (Rounded, 400, Apache-2.0) as CSS
// custom properties holding SVG data URIs, for the mask-based CSS icon engine.
// Run: node scripts/gen-icons.mjs   (re-run when adding icons to the list below)
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const dir = join(dirname(require.resolve('@material-symbols/svg-400/package.json')), 'rounded');

// token name -> Material Symbols file name
const ICONS = {
  mic: 'mic', 'mic-fill': 'mic-fill', present: 'present_to_all', pip: 'picture_in_picture_alt', 'call-end': 'call_end-fill',
  add: 'add', search: 'search', delete: 'delete', back: 'arrow_back', settings: 'settings',
  'light-mode': 'light_mode', 'dark-mode': 'dark_mode', 'system-mode': 'contrast',   translate: 'translate', send: 'send', copy: 'content_copy', download: 'download', mail: 'mail', share: 'share',
  minutes: 'description', ask: 'forum', check: 'check', close: 'close', lock: 'lock', cloud: 'cloud',
  play: 'play_arrow', chevron: 'keyboard_arrow_down', install: 'install_desktop', 'jump-down': 'arrow_downward',
  groups: 'groups', error: 'error', info: 'info',
};

const encode = (svg) => svg
  .replace(/\s(width|height)="[^"]*"/g, '')
  .replace(/"/g, "'")
  .replace(/[\r\n]+/g, '')
  .replace(/[<>#%{}]/g, encodeURIComponent);

// Hand-drawn icons (generic shapes, not from the Material set).
const CUSTOM = {
  // Four-point sparkle used for AI-generated content.
  spark: "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24'><path d='M12 2c.5 5.2 4.8 9.5 10 10-5.2.5-9.5 4.8-10 10-.5-5.2-4.8-9.5-10-10 5.2-.5 9.5-4.8 10-10Z'/></svg>",
};

const lines = Object.entries(ICONS).map(([token, file]) =>
  `  --icon-${token}: url("data:image/svg+xml,${encode(readFileSync(join(dir, `${file}.svg`), 'utf8'))}");`);

for (const [token, svg] of Object.entries(CUSTOM)) lines.push(`  --icon-${token}: url("data:image/svg+xml,${encode(svg)}");`);

writeFileSync('src/styles/icons.css',
  `/* Generated by scripts/gen-icons.mjs from @material-symbols/svg-400 (Rounded), Apache-2.0. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`);
console.log(`Wrote ${lines.length} icons`);
